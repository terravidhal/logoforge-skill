/**
 * Lightweight repository check: frontmatter, relative links, JSON files, and the
 * example assets. Runs in CI and locally with `npm run lint`.
 */
import { access, readFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const errors = [];
const warnings = [];

const required = [
  "README.md",
  "LICENSE",
  "TRADEMARKS.md",
  "CONTRIBUTING.md",
  "skills/logoforge/SKILL.md",
  "skills/logoforge/references/finding-logos.md",
  "skills/logoforge/references/installing.md",
  "skills/logoforge/references/missing-brand.md",
  "skills/logoforge/references/sections.md",
  "skills/logoforge/references/variants.md",
  "evals/evals.json",
  "examples/package.json",
  "examples/package-lock.json",
  "examples/app/page.tsx",
  "examples/app/layout.tsx",
  "examples/app/globals.css",
  "examples/README.md",
  "assets/readme/before-after.png",
  "assets/readme/example-desktop-light.png",
  "assets/readme/example-desktop-dark.png",
  "assets/readme/example-mobile-light.png",
  "assets/readme/example-mobile-dark.png",
  "assets/demo.gif",
];

const logoforgeComponents = [
  "figma",
  "github",
  "gitlab",
  "google",
  "linear",
  "notion",
  "stripe",
  "supabase",
  "vercel",
];

const markdownFiles = [
  "README.md",
  "TRADEMARKS.md",
  "CONTRIBUTING.md",
  "examples/README.md",
  "skills/logoforge/SKILL.md",
  "skills/logoforge/references/finding-logos.md",
  "skills/logoforge/references/installing.md",
  "skills/logoforge/references/missing-brand.md",
  "skills/logoforge/references/sections.md",
  "skills/logoforge/references/variants.md",
];

async function exists(relative) {
  try {
    await access(path.join(root, relative));
    return true;
  } catch {
    return false;
  }
}

for (const file of required) {
  if (!(await exists(file))) errors.push(`missing ${file}`);
}

for (const slug of logoforgeComponents) {
  const file = `examples/components/logos/${slug}.tsx`;
  if (!(await exists(file))) {
    errors.push(`missing vendored component ${file}`);
    continue;
  }
  const source = await readFile(path.join(root, file), "utf8");
  if (!source.includes("generated by Logoforge")) {
    errors.push(`${file} is not the registry output`);
  }
}

const skillFile = "skills/logoforge/SKILL.md";
if (await exists(skillFile)) {
  const source = await readFile(path.join(root, skillFile), "utf8");
  const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!frontmatter) {
    errors.push(`${skillFile} has no frontmatter`);
  } else {
    const block = frontmatter[1];
    const name = block.match(/^name:\s*(\S+)/m)?.[1];
    if (name !== "logoforge") errors.push(`${skillFile}: name must be logoforge`);
    if (!/^description:\s*\S/m.test(block)) {
      errors.push(`${skillFile}: description is missing`);
    }
    if (!/Logoforge/i.test(block) || !/logo/i.test(block)) {
      errors.push(`${skillFile}: description should mention logos and Logoforge`);
    }
  }

  const referenceLinks = [...source.matchAll(/\]\(references\/([^)#]+)\)/g)].map((m) => m[1]);
  for (const reference of new Set(referenceLinks)) {
    const file = `skills/logoforge/references/${reference}`;
    if (!(await exists(file))) errors.push(`${skillFile} links to missing ${file}`);
  }
}

for (const file of ["evals/evals.json", "examples/package.json", "examples/package-lock.json"]) {
  if (!(await exists(file))) continue;
  try {
    JSON.parse(await readFile(path.join(root, file), "utf8"));
  } catch (error) {
    errors.push(`${file}: invalid JSON (${error.message})`);
  }
}

for (const file of markdownFiles) {
  if (!(await exists(file))) continue;
  const source = await readFile(path.join(root, file), "utf8");
  const dir = path.dirname(file);
  const links = [...source.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)].map((m) => m[1]);
  for (const link of links) {
    if (/^(https?:|mailto:|#|\{)/.test(link)) continue;
    const [target] = link.split("#");
    if (!target) continue;
    const resolved = path.normalize(path.join(dir, target));
    if (!(await exists(resolved))) {
      warnings.push(`${file}: relative link not found: ${link}`);
    }
  }
}

for (const file of required.filter((entry) => entry.endsWith(".png"))) {
  if (!(await exists(file))) continue;
  const { size } = await stat(path.join(root, file));
  if (size < 10_000) errors.push(`${file} looks too small (${size} bytes)`);
}

if (await exists("assets/demo.gif")) {
  const file = path.join(root, "assets/demo.gif");
  const { size } = await stat(file);
  const header = (await readFile(file)).subarray(0, 6).toString("latin1");
  if (!header.startsWith("GIF8")) errors.push("assets/demo.gif is not a GIF");
  if (size < 10_000) errors.push(`assets/demo.gif looks too small (${size} bytes)`);
}

for (const warning of warnings) console.warn(`warning: ${warning}`);

if (errors.length > 0) {
  for (const error of errors) console.error(`error: ${error}`);
  console.error(`\n${errors.length} error(s)`);
  process.exit(1);
}

console.log(`ok: skill frontmatter, ${required.length} required files, links, JSON, assets`);
